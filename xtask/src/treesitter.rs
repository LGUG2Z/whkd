//! The tree-sitter grammar and its queries (Neovim, Helix, Zed, Emacs).
//!
//! The structure of `grammar.js` is written here; the words it matches (directives, shells, layouts,
//! keywords) and the modifier keys in the highlight queries come from the [`Vocabulary`], which is
//! read from the parser. The differential test checks the grammar against the parser itself.
//!
//! Commands follow the `.shell` directive through `injections.scm`: a pattern that pairs the
//! directive with each command embeds PowerShell or batch.

use crate::vocabulary::shells_in;
use crate::vocabulary::ShellFamily;
use crate::vocabulary::Vocabulary;
use whkd_core::GestureInput;
use whkd_core::MouseInput;
use whkd_parser::syntax;

const GRAMMAR: &str = r#"// @ts-check
/// <reference types="tree-sitter-cli/dsl" />

// Generated by `cargo xtask editors`. Do not edit.
//
// The structure is written in xtask/src/treesitter.rs. The words it matches (shells, layouts,
// directives, keywords) are read from the parser, and tests/the differential test in xtask check it
// against the parser itself.

/**
 * One or more `rule`s separated by `separator`
 * @param {RuleOrLiteral} rule
 * @param {RuleOrLiteral} separator
 */
function sep1(rule, separator) {
  return seq(rule, repeat(seq(separator, rule)));
}

module.exports = grammar({
  name: 'whkdrc',

  // newlines are not extras: a command, a hotkey and a process name all end at the end of the line
  extras: ($) => [/[ \t\r\f﻿]/, $.comment],

  rules: {
    // `@@SHELL@@` first, then the optional pause directives in that order, then the bindings
    source_file: ($) =>
      seq(
        optional($._eol),
        $.shell_directive,
        optional(seq($._eol, $.pause_directive)),
        optional(seq($._eol, $.pause_hook_directive)),
        optional(seq($._eol, $.wheel_cooldown_directive)),
        optional(seq($._eol, $.gesture_cooldown_directive)),
        repeat1(seq($._eol, $._item)),
        optional($._eol),
      ),

    _item: ($) => choice($.binding, $.block),

    shell_directive: ($) => seq('@@SHELL@@', $.shell_name),
    shell_name: ($) => choice(@@SHELLS@@),
    pause_directive: ($) => seq('@@PAUSE@@', $.hotkeys),
    pause_hook_directive: ($) => seq('@@PAUSE_HOOK@@', optional($.command)),
    wheel_cooldown_directive: ($) => seq('@@WHEEL_COOLDOWN@@', $.number),
    gesture_cooldown_directive: ($) => seq('@@GESTURE_COOLDOWN@@', $.number),
    number: (_) => /[0-9]+/,

    // keys : command, optionally guarded by `when` and a condition
    binding: ($) =>
      seq($.hotkeys, optional($.when_clause), '@@DELIMITER@@', optional($.command)),
    when_clause: ($) => seq('@@WHEN@@', $.condition),

    // keys [ condition : command ... ]
    block: ($) =>
      seq(
        $.hotkeys,
        '@@BLOCK_OPEN@@',
        $._eol,
        $.entry,
        repeat(seq($._eol, $.entry)),
        $._eol,
        '@@BLOCK_CLOSE@@',
      ),
    entry: ($) =>
      seq(choice($.default, $.condition), '@@DELIMITER@@', optional($.command)),
    default: (_) => '@@DEFAULT@@',

    condition: ($) => seq($._term, repeat(seq('@@AND@@', $._term))),
    _term: ($) => choice($.app_predicate, $.layout_predicate, $.process_name),
    app_predicate: ($) => seq('@@APP@@', $.comparison, sep1($.app_name, '@@OR@@')),
    layout_predicate: ($) =>
      seq('@@LAYOUT@@', $.comparison, sep1($.layout_name, '@@OR@@')),
    comparison: (_) => choice('@@EQUALS@@', '@@NOT_EQUALS@@'),

    // a bare process name, which may be spelt like a predicate when nothing follows it
    process_name: ($) => choice($._process_name, '@@APP@@', '@@LAYOUT@@'),

    // keys joined by `+`. A group, `{a,b}`, may also be next to a key or another group without one:
    // what it stands for has the `+` in it (`{_,shift +} {h,j}`)
    hotkeys: ($) =>
      seq($._hotkey_part, repeat(seq('@@KEY_SEPARATOR@@', $._hotkey_part))),
    // text can be next to a group, as `x{1,2}` and `{a,b}4up` are, and is a key once it has been
    // expanded
    _hotkey_part: ($) =>
      choice(
        $.key,
        seq(
          optional($.key),
          repeat1(seq($.group, optional(alias($._word, $.key)))),
        ),
      ),
    _word: (_) => /[\p{L}\p{N}_]+/,
    key: (_) => token(choice(/[\p{L}_][\p{L}\p{N}_]*/, /[0-9]+/)),

    // `{a,b}`, `{_,shift +}` and `{1-9}`: what is in it is for the parser to read
    group: ($) =>
      seq(
        '@@GROUP_OPEN@@',
        optional($.group_element),
        repeat(seq('@@GROUP_SEPARATOR@@', optional($.group_element))),
        '@@GROUP_CLOSE@@',
      ),
    group_element: (_) => /[^{},\r\n]+/,

    // the rest of the line, up to a comment. A `\` that ends a line, after a space (or at the start
    // of the command), goes on to the next
    command: (_) =>
      /(\\[ \t]*\r?\n[ \t]*)?[^#\s]([^#\r\n]|[ \t]\\[ \t]*\r?\n[ \t]*)*/,
    comment: (_) => token(/#[^\r\n]*/),

    // the values of the conditions. Several words make one process name (`Google Chrome`), but
    // only on one line
    app_name: (_) => /[\p{L}\p{N}_.-]+([ \t]+[\p{L}\p{N}_.-]+)*/,
    _process_name: (_) =>
      /[\p{L}_][\p{L}\p{N}_]*([ \t]+[\p{L}_][\p{L}\p{N}_]*)*/,
    // every spelling the parser accepts: case and separators are ignored
    layout_name: (_) => token(choice(@@LAYOUTS@@)),

    _eol: ($) => repeat1($._newline),
    _newline: (_) => /\r?\n/,
  },
});
"#;

pub fn grammar_js(vocabulary: &Vocabulary) -> String {
    let strings = |words: &[String]| {
        words
            .iter()
            .map(|word| format!("'{word}'"))
            .collect::<Vec<_>>()
            .join(", ")
    };

    let layouts = vocabulary
        .layouts
        .iter()
        .map(|layout| format!("/{}/", layout.pattern))
        .collect::<Vec<_>>()
        .join(", ");

    let [shell, pause, pause_hook] = [syntax::SHELL, syntax::PAUSE, syntax::PAUSE_HOOK];

    GRAMMAR
        .replace("@@SHELLS@@", &strings(&vocabulary.shells))
        .replace("@@LAYOUTS@@", &layouts)
        .replace("@@SHELL@@", shell)
        .replace("@@WHEEL_COOLDOWN@@", syntax::WHEEL_COOLDOWN)
        .replace("@@GESTURE_COOLDOWN@@", syntax::GESTURE_COOLDOWN)
        .replace("@@PAUSE_HOOK@@", pause_hook)
        .replace("@@PAUSE@@", pause)
        .replace("@@DELIMITER@@", &syntax::DELIMITER.to_string())
        .replace("@@WHEN@@", syntax::WHEN)
        .replace("@@BLOCK_OPEN@@", &syntax::BLOCK_OPEN.to_string())
        .replace("@@BLOCK_CLOSE@@", &syntax::BLOCK_CLOSE.to_string())
        .replace("@@DEFAULT@@", syntax::DEFAULT)
        .replace("@@AND@@", &syntax::AND.to_string())
        .replace("@@OR@@", &syntax::OR.to_string())
        .replace("@@APP@@", syntax::APP)
        .replace("@@LAYOUT@@", syntax::LAYOUT)
        .replace("@@NOT_EQUALS@@", syntax::NOT_EQUALS)
        .replace("@@EQUALS@@", &syntax::EQUALS.to_string())
        .replace("@@KEY_SEPARATOR@@", &syntax::KEY_SEPARATOR.to_string())
        .replace("@@GROUP_OPEN@@", &syntax::GROUP_OPEN.to_string())
        .replace("@@GROUP_CLOSE@@", &syntax::GROUP_CLOSE.to_string())
        .replace("@@GROUP_SEPARATOR@@", &syntax::GROUP_SEPARATOR.to_string())
}

/// `alt`, `Alt` and `ALT`: `#any-of?` compares exactly, and the regex dialects of the editors that
/// use these queries differ, so the likely spellings are listed
fn casings(words: &[String]) -> Vec<String> {
    let mut all = Vec::new();
    for word in words {
        let mut chars = word.chars();
        let capitalised = chars
            .next()
            .map(|first| first.to_uppercase().collect::<String>() + chars.as_str())
            .unwrap_or_default();

        for spelling in [word.clone(), capitalised, word.to_uppercase()] {
            if !all.contains(&spelling) {
                all.push(spelling);
            }
        }
    }
    all
}

/// How AutoHotkey, and so most people, spell a mouse input. An exhaustive match, so that a new one
/// has to be given a spelling
fn camel_case(input: MouseInput) -> &'static str {
    match input {
        MouseInput::LButton => "LButton",
        MouseInput::RButton => "RButton",
        MouseInput::MButton => "MButton",
        MouseInput::XButton1 => "XButton1",
        MouseInput::XButton2 => "XButton2",
        MouseInput::WheelUp => "WheelUp",
        MouseInput::WheelDown => "WheelDown",
        MouseInput::WheelLeft => "WheelLeft",
        MouseInput::WheelRight => "WheelRight",
    }
}

/// How the gestures are spelt in camel case: an exhaustive match, so that a new one has to be given
/// a spelling
fn gesture_camel_case(input: GestureInput) -> &'static str {
    match input {
        GestureInput::Swipe3 => "Swipe3",
        GestureInput::Swipe4 => "Swipe4",
        GestureInput::Swipe3Left => "Swipe3Left",
        GestureInput::Swipe3Right => "Swipe3Right",
        GestureInput::Swipe3Up => "Swipe3Up",
        GestureInput::Swipe3Down => "Swipe3Down",
        GestureInput::Swipe4Left => "Swipe4Left",
        GestureInput::Swipe4Right => "Swipe4Right",
        GestureInput::Swipe4Up => "Swipe4Up",
        GestureInput::Swipe4Down => "Swipe4Down",
    }
}

pub fn highlights(vocabulary: &Vocabulary) -> String {
    let directives = syntax::DIRECTIVES
        .iter()
        .map(|directive| format!("\"{directive}\""))
        .collect::<Vec<_>>()
        .join(" ");

    let modifiers = casings(&vocabulary.modifiers)
        .iter()
        .map(|modifier| format!("\"{modifier}\""))
        .collect::<Vec<_>>()
        .join(" ");

    // `#any-of?` is exact, so the spelling people know these by (`WheelUp`, `MButton`) is added
    let mut mouse_spellings = casings(&vocabulary.mouse_inputs);
    mouse_spellings.extend(MouseInput::ALL.map(|input| camel_case(input).to_string()));
    mouse_spellings.dedup();

    let mouse_inputs = mouse_spellings
        .iter()
        .map(|input| format!("\"{input}\""))
        .collect::<Vec<_>>()
        .join(" ");

    let mut gesture_spellings = casings(&vocabulary.gestures);
    gesture_spellings.extend(GestureInput::ALL.map(|input| gesture_camel_case(input).to_string()));
    gesture_spellings.dedup();

    let gestures = gesture_spellings
        .iter()
        .map(|input| format!("\"{input}\""))
        .collect::<Vec<_>>()
        .join(" ");

    format!(
        r#"; Generated by `cargo xtask editors`. Do not edit.

(comment) @comment

[{directives}] @keyword.directive

(shell_name) @constant.builtin
(number) @number

"{when}" @keyword.conditional
(default) @keyword

(key) @constant

; modifier keys are told apart from the others by name
((key) @keyword.modifier
  (#any-of? @keyword.modifier {modifiers}))

; and so are mouse buttons and scroll directions
((key) @constant.builtin
  (#any-of? @constant.builtin {mouse_inputs}))

; and the swipes of a touchpad
((key) @constant.builtin
  (#any-of? @constant.builtin {gestures}))

["{key_separator}" "{and}" "{or}" "{equals}" "{not_equals}"] @operator

["{delimiter}"] @punctuation.delimiter
["{block_open}" "{block_close}"] @punctuation.bracket

; `{{a,b}}`: the elements of a group are keys, but are only read when it is expanded
(group ["{group_open}" "{group_close}"] @punctuation.special)
(group "{group_separator}" @punctuation.delimiter)
(group_element) @constant

(app_predicate "{app}" @variable.parameter)
(layout_predicate "{layout}" @variable.parameter)

(layout_name) @constant.builtin
(app_name) @type
(process_name) @type

; `{ignore}` as a whole command does nothing, and says so
((command) @keyword
  (#any-of? @keyword "{ignore}"))

(ERROR) @error
"#,
        when = syntax::WHEN,
        key_separator = syntax::KEY_SEPARATOR,
        and = syntax::AND,
        or = syntax::OR,
        equals = syntax::EQUALS,
        not_equals = syntax::NOT_EQUALS,
        delimiter = syntax::DELIMITER,
        block_open = syntax::BLOCK_OPEN,
        block_close = syntax::BLOCK_CLOSE,
        group_open = syntax::GROUP_OPEN,
        group_close = syntax::GROUP_CLOSE,
        group_separator = syntax::GROUP_SEPARATOR,
        app = syntax::APP,
        layout = syntax::LAYOUT,
        ignore = syntax::IGNORE,
    )
}

/// Embed the shell's language in every command, chosen by the `.shell` directive. A query pattern
/// may pair siblings, so each pattern here matches the directive together with one command
pub fn injections() -> String {
    let places = [
        "(binding (command) @injection.content)",
        "(block (entry (command) @injection.content))",
        "(pause_hook_directive (command) @injection.content)",
    ];

    let mut out = String::from("; Generated by `cargo xtask editors`. Do not edit.\n");

    for (family, language) in [
        (ShellFamily::PowerShell, "powershell"),
        (ShellFamily::Batch, "batch"),
    ] {
        let shells = shells_in(family)
            .iter()
            .map(|shell| format!("\"{shell}\""))
            .collect::<Vec<_>>()
            .join(" ");

        for place in places {
            out.push_str(&format!(
                "\n((source_file\n  (shell_directive (shell_name) @_shell)\n  {place})\n  (#any-of? @_shell {shells})\n  (#set! injection.language \"{language}\"))\n"
            ));
        }
    }

    out
}

pub fn folds() -> String {
    String::from("; Generated by `cargo xtask editors`. Do not edit.\n\n(block) @fold\n")
}
